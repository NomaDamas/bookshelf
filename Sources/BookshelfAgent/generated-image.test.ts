for (const usePi of [true, false]) {
	test(`Official Codex image events persist before an image-only answer (Pi=${usePi})`, async () => {
		const root = await mkdtemp(join(tmpdir(), "bookshelf-image-event-"));
		try {
			const events: any[] = [];
			await handle(
				{
					action: "chat",
					backend: "codex",
					usePi,
					skill: "auto",
					workspace: root,
					codexHome: join(root, "Codex"),
					assetDirectory: join(root, "ChatAssets"),
					codexPath: await fixture(root, "success"),
					question: "Explain this with an illustration",
					messages: [],
					book: {
						id: "test",
						title: "Test",
						page: 1,
						text: "Example",
						notes: "",
						selection: "",
					},
				},
				new AbortController().signal,
				(event) => events.push(event),
			);
			const images = events.filter((e) => e.type === "attachment");
			expect(images).toHaveLength(1);
			expect(
				(await stat(join(root, "ChatAssets", images[0].attachment.fileName)))
					.size,
			).toBeGreaterThan(2_000_000);
			expect(events.at(-1)).toMatchObject({ type: "answer", text: "" });
			expect(events.some((e) => e.type === "activity" && e.message)).toBe(true);
		} finally {
			await rm(root, { recursive: true, force: true });
		}
	});
}

for (const mode of ["failed", "unexpected", "cancel"]) {
	test(`Codex ${mode} does not claim a generated image`, async () => {
		const root = await mkdtemp(join(tmpdir(), "bookshelf-image-failure-"));
		try {
			const events: any[] = [],
				abort = new AbortController();
			const task = handle(
				{
					action: "chat",
					backend: "codex",
					usePi: true,
					skill: "auto",
					workspace: root,
					codexHome: join(root, "Codex"),
					assetDirectory: join(root, "ChatAssets"),
					codexPath: await fixture(root, mode),
					question: "Create an image",
					messages: [],
					book: { id: "test", page: 1, text: "Example" },
				},
				abort.signal,
				(event) => {
					events.push(event);
					if (mode === "cancel" && event.type === "activity") abort.abort();
				},
			);
			if (mode === "failed") {
				await task;
				expect(events.some((e) => e.type === "warning")).toBe(true);
			} else {
				await expect(task).rejects.toThrow();
				expect(events.some((e) => e.type === "answer")).toBe(false);
			}
			expect(events.some((e) => e.type === "attachment")).toBe(false);
		} finally {
			await rm(root, { recursive: true, force: true });
		}
	});
}
