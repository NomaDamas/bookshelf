test("Generated bytes get private UUID paths; unsafe, non-image and oversized dimensions are rejected", async () => {
	const root = await mkdtemp(join(tmpdir(), "bookshelf-image-test-"));
	try {
		const directory = join(root, "ChatAssets");
		const attachment = await saveGeneratedImage(png, directory);
		expect(attachment.kind).toBe("image");
		expect(attachment.fileName).toMatch(/^[0-9a-f-]{36}\.png$/);
		expect(await readFile(join(directory, attachment.fileName))).toEqual(
			Buffer.from(png, "base64"),
		);
		expect(
			(await stat(join(directory, attachment.fileName))).mode & 0o777,
		).toBe(0o600);
		for (const invalid of [
			"",
			"../private.png",
			"%%%",
			Buffer.from("not an image").toString("base64"),
		])
			await expect(saveGeneratedImage(invalid, directory)).rejects.toThrow();
		const huge = Buffer.from(png, "base64");
		huge.writeUInt32BE(100000, 16);
		huge.writeUInt32BE(100000, 20);
		await expect(
			saveGeneratedImage(huge.toString("base64"), directory),
		).rejects.toThrow();
		await symlink(directory, join(root, "linked"));
		await expect(
			saveGeneratedImage(png, join(root, "linked")),
		).rejects.toThrow();
		expect(await readdir(directory)).toHaveLength(1);
	} finally {
		await rm(root, { recursive: true, force: true });
	}
});

