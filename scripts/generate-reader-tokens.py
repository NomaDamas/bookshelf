#!/usr/bin/env python3
"""Generate the native style constants from the app's design token source."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='Fail if generated Swift is stale.')
args = parser.parse_args()
source = root / 'Resources/Design/tokens.json'
target = root / 'Sources/BookshelfApp/ReaderTokens.swift'
tokens = json.loads(source.read_text(encoding='utf-8'))['native']
lines = ['// Generated by scripts/generate-reader-tokens.py. Edit Resources/Design/tokens.json.',
         'import Foundation', '', 'enum ReaderTokens {']
for name, token in tokens.items():
    value = token['$value']
    if token['$type'] == 'dimension':
        if value['unit'] != 'px':
            raise ValueError(f'{name}: native dimensions must use px (mapped to points)')
        value, swift_type = value['value'], 'CGFloat'
    elif token['$type'] == 'number':
        swift_type = 'Double'
    else:
        raise ValueError(f'{name}: unsupported token type')
    if not name.isidentifier() or isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError(f'{name}: invalid token')
    lines.append(f'    static let {name}: {swift_type} = {value}')
text = '\n'.join([*lines, '}', ''])
if args.check:
    if not target.exists() or target.read_text(encoding='utf-8') != text:
        raise SystemExit('ReaderTokens.swift is stale; run scripts/generate-reader-tokens.py')
    print('Reader tokens are current.')
else:
    target.write_text(text, encoding='utf-8')
    print(f'Generated {target.relative_to(root)}')
